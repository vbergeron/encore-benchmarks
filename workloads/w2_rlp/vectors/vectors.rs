// W2 input vectors, shared by every variant through `include!`.
//
// Each case is the EIP-155 signing payload of a legacy Ethereum
// transaction, `rlp([nonce, gasPrice, gasLimit, to, value, data, chainId,
// 0, 0])`, as a host sends it to a hardware wallet. N = size of the
// calldata in bytes: a plain transfer, a call without arguments, an ERC-20
// transfer, and a contract call with eight 32-byte arguments. Together
// they use every RLP form: single bytes (0x00..0x7f), short and long
// strings (0xb8), short and long lists (0xf8, 0xf9), and empty strings
// for zero. The comments give the structure; the expected screen of each
// case is in the R variant.

/// Size parameter of each case (calldata bytes), in increasing order.
pub const CASES: &[u32] = &[0, 4, 68, 260];

/// The signing payload of the case with `n` bytes of calldata.
pub fn payload(n: u32) -> &'static [u8] {
    match n {
        0 => &TX_0,
        4 => &TX_4,
        68 => &TX_68,
        260 => &TX_260,
        _ => &[],
    }
}

