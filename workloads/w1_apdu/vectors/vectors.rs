// W1 input vectors, shared by every variant through `include!`.
//
// N = size of the command APDU in bytes: one APDU per case, from a bare
// case-2 command (header and Le) to a case-4 command whose data field is
// the maximal 255 bytes. The data fields are BER-TLV structures as a card
// receives them: an EMV record, an FCI template and a card-verifiable
// certificate (EAC), nested up to depth 3, with one- and two-byte tags and
// one-byte and 0x81 lengths. The comments give the structure; the
// expected output of each case is in the R variant.

/// Size parameter of each case (APDU bytes), in increasing order.
pub const CASES: &[u32] = &[5, 32, 128, 261];

/// Largest N in `CASES`.
pub const MAX_APDU: usize = 261;

/// The command APDU of the case of size `n`.
pub fn apdu(n: u32) -> &'static [u8] {
    match n {
        5 => &APDU_5,
        32 => &APDU_32,
        128 => &APDU_128,
        261 => &APDU_261,
        _ => &[],
    }
}

